  id BIGINT generated by default as identity primary key,
  created_at TIMESTAMPTZ default now(),
  user_id UUID references public.profiles(id) on delete cascade not null,
  content TEXT not null,
  media_url TEXT
);

-- ---------------------------------------------------------------------
--  3.  CONNECTIONS  (unchanged)
-- ---------------------------------------------------------------------
create table if not exists public.connections (
  id BIGINT generated by default as identity primary key,
  created_at TIMESTAMPTZ default now(),
  requester_id UUID references public.profiles(id) on delete cascade not null,
  receiver_id UUID references public.profiles(id) on delete cascade not null,
  status TEXT default 'pending' check (status in ('pending', 'accepted', 'rejected', 'blocked')),
  constraint unique_connection unique (requester_id, receiver_id)
);

-- ---------------------------------------------------------------------
--  4.  OFFERS  (unchanged) — Rapido-style price negotiation
-- ---------------------------------------------------------------------
create table if not exists public.offers (
  id BIGINT generated by default as identity primary key,
  created_at TIMESTAMPTZ default now(),
  post_id BIGINT references public.posts(id) on delete cascade,
  employer_id UUID references public.profiles(id) on delete cascade not null,
  worker_id UUID references public.profiles(id) on delete cascade not null,
  offered_price NUMERIC(10, 2) not null,
  status TEXT default 'pending' check (status in ('pending', 'accepted', 'declined', 'countered'))
);


