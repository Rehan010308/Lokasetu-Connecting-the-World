const DICTS: Record<LangCode, Dict> = { en, hi, ta, te, ml, kn };

/** Translate a UI key. Falls back to English if a language is missing a key. */
export function t(lang: LangCode, key: TKey): string {
  const d = DICTS[lang] || {};
  return (d[key] as string) || (en[key] as string) || key;
}

/** Convenience: bind a language once, then call tt('c.continue'). */
export function makeT(lang: LangCode) {
  return (key: TKey) => t(lang, key);
}

export function langName(code: LangCode): string {
  return LANGUAGES.find((l) => l.code === code)?.native ?? code;
}

export function speechLocale(code: LangCode): string {
  return LANGUAGES.find((l) => l.code === code)?.speech ?? 'en-IN';
}
